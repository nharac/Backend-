-- ============================================
-- V25: Sumi Monedas y vestidor de Sumi
-- ============================================
-- Las Sumi Monedas son una moneda aparte de los Puntos Sumi: los puntos siguen siendo
-- para el ranking y las monedas se gastan en el vestidor (gorros, gafas, objetos,
-- espaldas, bufandas y fondos). Las compras y lo que Sumi lleva puesto se guardan aquí
-- para que no se puedan alterar desde el navegador y sigan a la persona en cualquier equipo.

-- 1. Saldo de cada usuario (se descuenta con un UPDATE condicionado: nunca queda negativo)
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS monedas INT NOT NULL DEFAULT 0;
ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS ck_usuarios_monedas_no_negativas;
ALTER TABLE usuarios ADD CONSTRAINT ck_usuarios_monedas_no_negativas CHECK (monedas >= 0);

-- 2. Historial de monedas ganadas (+) y gastadas (-)
CREATE TABLE IF NOT EXISTS monedas_historial (
    id BIGSERIAL PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    cantidad INT NOT NULL,
    motivo VARCHAR(150) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_monedas_historial_usuario_fecha ON monedas_historial (usuario_id, fecha DESC);

-- 3. Catálogo con los precios (el frontend tiene los mismos en estilo-sumi.service.ts)
CREATE TABLE IF NOT EXISTS sumi_catalogo (
    categoria VARCHAR(20) NOT NULL,
    prenda VARCHAR(40) NOT NULL,
    precio INT NOT NULL CHECK (precio >= 0),
    PRIMARY KEY (categoria, prenda)
);

-- 4. Lo que cada usuario compró
CREATE TABLE IF NOT EXISTS sumi_inventario (
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    categoria VARCHAR(20) NOT NULL,
    prenda VARCHAR(40) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (usuario_id, categoria, prenda),
    FOREIGN KEY (categoria, prenda) REFERENCES sumi_catalogo (categoria, prenda)
);

-- 5. Lo que Sumi lleva puesto
CREATE TABLE IF NOT EXISTS sumi_estilo (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
    sombrero VARCHAR(40) NOT NULL DEFAULT 'ninguno',
    cara VARCHAR(40) NOT NULL DEFAULT 'ninguno',
    objeto VARCHAR(40) NOT NULL DEFAULT 'ninguno',
    espalda VARCHAR(40) NOT NULL DEFAULT 'ninguno',
    bufanda VARCHAR(40) NOT NULL DEFAULT 'saesu',
    fondo VARCHAR(40) NOT NULL DEFAULT 'ninguno',
    actualizado TIMESTAMP NOT NULL DEFAULT NOW()
);

