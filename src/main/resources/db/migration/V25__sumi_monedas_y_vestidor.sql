-- 7. Bono de bienvenida: los estudiantes que ya tenían puntos arrancan con la quinta parte en monedas
INSERT INTO monedas_historial (usuario_id, cantidad, motivo, fecha)
SELECT u.id, SUM(p.cantidad) / 5, 'Bono de bienvenida a las Sumi Monedas', NOW()
FROM usuarios u JOIN puntos_historial p ON p.usuario_id = u.id
WHERE u.rol = 'ESTUDIANTE'
  AND NOT EXISTS (SELECT 1 FROM monedas_historial m WHERE m.usuario_id = u.id AND m.motivo = 'Bono de bienvenida a las Sumi Monedas')
GROUP BY u.id
HAVING SUM(p.cantidad) / 5 > 0;

UPDATE usuarios u SET monedas = COALESCE((SELECT SUM(m.cantidad) FROM monedas_historial m WHERE m.usuario_id = u.id), 0);
